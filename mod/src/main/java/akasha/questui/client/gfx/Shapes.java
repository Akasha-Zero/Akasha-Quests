package akasha.questui.client.gfx;

import java.io.InputStreamReader;
import java.io.Reader;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.Collections;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

import net.minecraft.client.Minecraft;
import net.minecraft.client.renderer.texture.TextureManager;
import net.minecraft.util.ResourceLocation;

import com.google.gson.JsonArray;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;

import akasha.questui.AkashaQuestUI;

/**
 * Quest shapes (DESIGN §2): textures generated by tools/gen_textures.py and the exact polygons from
 * shapes/shapes.json, so hit-testing uses the very geometry that is drawn.
 */
public final class Shapes {

    public static final String NONE = "none";
    private static final String DOMAIN = "akashaquestui";

    /** Display order of the shape picker, FTB Quests' set first. */
    public static final List<String> ORDER = Collections.unmodifiableList(
        java.util.Arrays.asList(
            "circle",
            "square",
            "rsquare",
            "diamond",
            "pentagon",
            "hexagon",
            "octagon",
            "heart",
            "gear",
            "star",
            NONE));

    private static final Map<String, Shape> SHAPES = new LinkedHashMap<>();

    private Shapes() {}

    public static final class Shape {

        public final String id;
        private final float[] xs;
        private final float[] ys;
        public final MipTexture fill;
        public final MipTexture outline;
        public final MipTexture mask;
        public final MipTexture glow;

        Shape(String id, float[] xs, float[] ys, MipTexture fill, MipTexture outline, MipTexture mask,
            MipTexture glow) {
            this.id = id;
            this.xs = xs;
            this.ys = ys;
            this.fill = fill;
            this.outline = outline;
            this.mask = mask;
            this.glow = glow;
        }

        /** Even-odd point-in-polygon test in the unit frame [-1, 1]^2. */
        public boolean contains(double u, double v) {
            if (xs == null) return Math.abs(u) <= 1 && Math.abs(v) <= 1;
            boolean in = false;
            int n = xs.length;
            for (int i = 0, j = n - 1; i < n; j = i++) {
                if ((ys[i] > v) != (ys[j] > v) && u < (xs[j] - xs[i]) * (v - ys[i]) / (ys[j] - ys[i]) + xs[i]) {
                    in = !in;
                }
            }
            return in;
        }

        public boolean isNone() {
            return xs == null;
        }
    }

    /** Loads polygons and registers the textures with the texture manager (reloaded with resource packs). */
    public static void load() {
        SHAPES.clear();
        TextureManager tm = Minecraft.getMinecraft()
            .getTextureManager();
        JsonObject root;
        try (Reader r = new InputStreamReader(
            Minecraft.getMinecraft()
                .getResourceManager()
                .getResource(new ResourceLocation(DOMAIN, "shapes/shapes.json"))
                .getInputStream(),
            StandardCharsets.UTF_8)) {
            root = new JsonParser().parse(r)
                .getAsJsonObject();
        } catch (Exception e) {
            AkashaQuestUI.LOG.error("Unable to read shapes.json", e);
            return;
        }
        JsonObject shapes = root.getAsJsonObject("shapes");
        for (String id : ORDER) {
            if (NONE.equals(id)) {
                SHAPES.put(id, new Shape(id, null, null, null, null, null, null));
                continue;
            }
            JsonArray pts = shapes.getAsJsonArray(id);
            if (pts == null) continue;
            float[] xs = new float[pts.size()];
            float[] ys = new float[pts.size()];
            for (int i = 0; i < pts.size(); i++) {
                JsonArray p = pts.get(i)
                    .getAsJsonArray();
                xs[i] = p.get(0)
                    .getAsFloat();
                ys[i] = p.get(1)
                    .getAsFloat();
            }
            SHAPES.put(
                id,
                new Shape(
                    id,
                    xs,
                    ys,
                    texture(tm, "textures/shapes/" + id + "_fill.png", false),
                    texture(tm, "textures/shapes/" + id + "_outline.png", false),
                    texture(tm, "textures/shapes/" + id + "_mask.png", false),
                    texture(tm, "textures/shapes/" + id + "_glow.png", false)));
        }
    }

    public static MipTexture texture(TextureManager tm, String path, boolean repeatU) {
        ResourceLocation rl = new ResourceLocation(DOMAIN, path);
        MipTexture tex = new MipTexture(rl, repeatU);
        tm.loadTexture(rl, tex);
        return tex;
    }

    public static Shape get(String id) {
        if (SHAPES.isEmpty()) load();
        Shape s = SHAPES.get(id);
        return s != null ? s : SHAPES.get("circle");
    }

    public static boolean exists(String id) {
        return ORDER.contains(id);
    }

    public static List<String> ids() {
        return new ArrayList<>(ORDER);
    }
}
